"""
models.py — Locked PostgreSQL Database Schema for Learn2Lead (All 3 Modules).
DO NOT EDIT THIS FILE in Module 1, 2, or 3 so all team members stay 100% compatible!
"""
from datetime import datetime
from sqlalchemy import (
    Column, Integer, String, Float, Boolean, DateTime, ForeignKey, JSON, Text
)
from .database import Base


class User(Base):
    """1. Student and Admin accounts."""
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String(120), nullable=False)
    email = Column(String(150), unique=True, index=True, nullable=False)
    password_hash = Column(String(255), nullable=False)
    role = Column(String(20), default="student")  # 'student' | 'admin'
    selected_domain = Column(String(120), default="DevOps & Cloud Engineering")
    is_active = Column(Boolean, default=True)
    created_at = Column(DateTime, default=datetime.utcnow)


class Subject(Base):
    """2. Academic subjects (student-owned or Admin global subjects)."""
    __tablename__ = "subjects"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=True)
    name = Column(String(150), nullable=False)
    difficulty = Column(String(30), default="Medium")  # Easy | Medium | Hard
    target_hours_per_week = Column(Float, default=5.0)
    exam_deadline = Column(String(30), nullable=True)  # YYYY-MM-DD
    is_global = Column(Boolean, default=False)
    created_at = Column(DateTime, default=datetime.utcnow)


class StudyTask(Base):
    """3. Daily and weekly study planner tasks."""
    __tablename__ = "study_tasks"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    subject_id = Column(Integer, ForeignKey("subjects.id"), nullable=True)
    title = Column(String(200), nullable=False)
    scheduled_date = Column(String(30), nullable=False)  # YYYY-MM-DD
    duration_mins = Column(Integer, default=45)
    priority = Column(String(20), default="Medium")  # Low | Medium | High
    status = Column(String(30), default="pending")   # pending | completed | missed
    created_at = Column(DateTime, default=datetime.utcnow)


class Quiz(Base):
    """4. Quizzes & Mock Tests across Academic, Aptitude, and Career Domains."""
    __tablename__ = "quizzes"

    id = Column(Integer, primary_key=True, index=True)
    category = Column(String(40), nullable=False)  # academic | aptitude | technical | mock_test
    subject_or_domain = Column(String(120), nullable=False)
    topic = Column(String(150), nullable=False)
    title = Column(String(200), nullable=False)
    duration_mins = Column(Integer, default=15)
    created_by = Column(Integer, ForeignKey("users.id"), nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)


class Question(Base):
    """5. Individual quiz questions (MCQs, True/False, Short Answer)."""
    __tablename__ = "questions"

    id = Column(Integer, primary_key=True, index=True)
    quiz_id = Column(Integer, ForeignKey("quizzes.id"), nullable=False)
    question_text = Column(Text, nullable=False)
    question_type = Column(String(30), default="mcq")  # mcq | true_false | short_answer
    options_json = Column(JSON, default=list)          # ["Option A", "Option B", ...]
    correct_answer = Column(String(255), nullable=False)
    topic_tag = Column(String(120), nullable=True)
    explanation = Column(Text, nullable=True)


class QuizAttempt(Base):
    """6. Student quiz submissions, scores, and weak topics."""
    __tablename__ = "quiz_attempts"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    quiz_id = Column(Integer, ForeignKey("quizzes.id"), nullable=False)
    score_percent = Column(Float, nullable=False)
    answers_json = Column(JSON, default=dict)
    weak_topics_json = Column(JSON, default=list)
    completed_at = Column(DateTime, default=datetime.utcnow)


class CareerDomain(Base):
    """7. Employability career tracks (Data Analytics, DevOps, SWE, etc.)."""
    __tablename__ = "career_domains"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String(120), unique=True, nullable=False)
    description = Column(Text, nullable=False)
    growth_rate_percent = Column(Float, default=18.0)
    avg_salary_range = Column(String(80), default="6–14 LPA")


class RoadmapStep(Base):
    """8. Ordered learning steps inside each Career Domain roadmap."""
    __tablename__ = "roadmap_steps"

    id = Column(Integer, primary_key=True, index=True)
    domain_id = Column(Integer, ForeignKey("career_domains.id"), nullable=False)
    step_order = Column(Integer, nullable=False)
    skill_name = Column(String(150), nullable=False)
    description = Column(Text, nullable=True)
    resources_json = Column(JSON, default=list)  # [{"title": "...", "url": "..."}]
    linked_quiz_id = Column(Integer, ForeignKey("quizzes.id"), nullable=True)


class StudentRoadmapProgress(Base):
    """9. Tracks each student's completed skills in a Career Roadmap."""
    __tablename__ = "student_roadmap_progress"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    domain_id = Column(Integer, ForeignKey("career_domains.id"), nullable=False)
    step_id = Column(Integer, ForeignKey("roadmap_steps.id"), nullable=False)
    status = Column(String(30), default="not_started")  # not_started | in_progress | completed
    updated_at = Column(DateTime, default=datetime.utcnow)


class ReadinessConfig(Base):
    """10. Admin-configurable weights for Placement Readiness Score (must sum to 100)."""
    __tablename__ = "readiness_config"

    id = Column(Integer, primary_key=True, index=True)
    aptitude_weight = Column(Float, default=15.0)
    logical_weight = Column(Float, default=15.0)
    verbal_weight = Column(Float, default=10.0)
    technical_weight = Column(Float, default=25.0)
    roadmap_weight = Column(Float, default=15.0)
    mock_test_weight = Column(Float, default=20.0)
    updated_at = Column(DateTime, default=datetime.utcnow)


class ReadinessHistory(Base):
    """11. Historical snapshots of Placement Readiness Scores for growth charts."""
    __tablename__ = "readiness_history"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    overall_score = Column(Float, nullable=False)
    category_scores_json = Column(JSON, default=dict)
    recorded_at = Column(DateTime, default=datetime.utcnow)


class RecommendationLog(Base):
    """12. AI Study Recommendation history and before/after improvement tracking."""
    __tablename__ = "recommendation_logs"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    recommended_topic = Column(String(180), nullable=False)
    reason = Column(Text, nullable=False)
    suggested_date = Column(String(30), nullable=True)
    pre_score = Column(Float, nullable=True)
    post_score = Column(Float, nullable=True)
    status = Column(String(30), default="suggested")  # suggested | followed | improved
    created_at = Column(DateTime, default=datetime.utcnow)


class MarketTrend(Base):
    """13. Job Market Trends & Industry Insights linked to Career Domains."""
    __tablename__ = "market_trends"

    id = Column(Integer, primary_key=True, index=True)
    domain_id = Column(Integer, ForeignKey("career_domains.id"), nullable=False)
    role_title = Column(String(150), nullable=False)
    demand_index = Column(Integer, default=80)       # 0 to 100
    in_demand_skills_json = Column(JSON, default=list)
    hiring_trend_json = Column(JSON, default=dict)   # {"2024": 70, "2025": 82, "2026": 91}
    source_name = Column(String(150), default="Industry Hiring Benchmark")
    updated_at = Column(DateTime, default=datetime.utcnow)
